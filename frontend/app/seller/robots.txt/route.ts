import { originForSite } from '@/lib/site';

/**
 * robots.txt for the SELLER property (seller.throttlein.com).
 *
 * Served at `seller.throttlein.com/robots.txt` via the rewrite in
 * proxy.ts. A route handler rather than the `robots.ts` convention
 * because Next's convention is per-path, and one app answers for two
 * hosts.
 *
 * Critically, `Sitemap:` points at the SELLER sitemap. Pointing it at the
 * main one would invite Google to crawl throttlein.com URLs from the
 * seller host and treat the properties as duplicates.
 *
 * ── ON THE TRAILING SLASHES ──────────────────────────────────────
 * `Disallow: /login/` does NOT match `/login`. A robots.txt rule is a
 * prefix match on the literal string, so a trailing slash makes the rule
 * cover the directory's CONTENTS while leaving the bare path crawlable.
 * The seller property's auth screens live at `/login` and `/register`
 * with no trailing segment, so each such rule is paired with a
 * slash-less variant. Without the pair, the login page stays indexable —
 * which is the opposite of what these rules are for.
 *
 * Several disallowed paths (checkout, payments, moderator, …) have no
 * route on this property today. They're kept deliberately: a rule for a
 * path that doesn't exist costs nothing, and it means adding the route
 * later can't silently expose it.
 */

export const revalidate = 3600;

export async function GET() {
  const origin = originForSite('seller');

  const body = [
    '# robots.txt for seller.throttlein.com',
    '# Purpose: Control crawler access to the seller portal while',
    '# protecting sensitive seller data.',
    '#',
    '# Generated by app/seller/robots.txt/route.ts - edit there, not by',
    '# hand, and note that the Sitemap line below is derived from the',
    '# configured seller origin so dev and staging advertise themselves',
    '# rather than production.',
    '',
    '# ============================================',
    '# CORE RULES - Allow broad crawling',
    '# ============================================',
    'User-Agent: *',
    'Allow: /',
    'Allow: /*?q=',
    'Allow: /*?category=',
    'Allow: /*?location=',
    '',
    '# ============================================',
    '# BLOCK SENSITIVE SELLER AREAS',
    '# ============================================',
    '',
    '# Seller account management (critical to block)',
    'Disallow: /dashboard',
    'Disallow: /dashboard/',
    'Disallow: /account/',
    'Disallow: /profile/',
    'Disallow: /settings/',
    'Disallow: /orders/',
    'Disallow: /payments/',
    'Disallow: /payouts/',
    'Disallow: /withdraw/',
    '',
    '# Authentication & checkout (protect transactions)',
    // Bare paths first — these are the real routes on this property.
    'Disallow: /login',
    'Disallow: /login/',
    'Disallow: /register',
    'Disallow: /register/',
    'Disallow: /signup',
    'Disallow: /signup/',
    'Disallow: /logout',
    'Disallow: /logout/',
    'Disallow: /reset-password',
    'Disallow: /reset-password/',
    'Disallow: /checkout/',
    'Disallow: /cart',
    '',
    '# Admin areas',
    'Disallow: /admin/',
    'Disallow: /super-admin/',
    'Disallow: /moderator/',
    '',
    '# API & technical endpoints',
    'Disallow: /api/',
    'Disallow: /webhook/',
    'Disallow: /webhooks/',
    '',
    '# Seller onboarding (block until completed)',
    'Disallow: /onboarding/',
    'Disallow: /verify-email/',
    'Disallow: /kyc/',
    // `/verify/<token>` is the real email-verification route on this
    // property — one-time links that must never be indexed.
    'Disallow: /verify',
    'Disallow: /verify/',
    'Disallow: /verification/',
    '',
    '# Pagination & sorting (prevent duplicate content)',
    'Disallow: /*?sort=',
    'Disallow: /*?page=',
    'Disallow: /*?filter=',
    'Disallow: /*?per_page=',
    '',
    '# CDN & internal paths',
    'Disallow: /cdn-cgi/',
    'Disallow: /assets/internal/',
    'Disallow: /temp/',
    'Disallow: /cache/',
    '',
    '# ============================================',
    '# AI BOT POLICIES - Allow crawling',
    '# ============================================',
    '',
    "# Google-Extended (Google's AI training signal) - Allow full access",
    'User-Agent: Google-Extended',
    'Allow: /',
    '',
    '# GPTBot (OpenAI) - Allow full access',
    'User-Agent: GPTBot',
    'Allow: /',
    '',
    '# Common AI crawlers - Allow full access',
    'User-Agent: ChatGPT-User',
    'Allow: /',
    '',
    'User-Agent: ClaudeBot',
    'Allow: /',
    '',
    '# ============================================',
    '# SITEMAP LOCATION',
    '# ============================================',
    `Sitemap: ${origin}/sitemap.xml`,
    '',
    '# ============================================',
    '# LLM GUIDE',
    '# ============================================',
    '# Curated map of this property for language models (llmstxt.org).',
    `# ${origin}/llms.txt`,
    '',
  ].join('\n');

  return new Response(body, {
    headers: {
      // `charset=utf-8` is not optional. Without it the browser (and some
      // crawlers) fall back to a legacy encoding and any non-ASCII
      // character in a comment renders as mojibake — an em dash came out
      // as "â€”" before this was set.
      'Content-Type': 'text/plain; charset=utf-8',
      'Cache-Control': 'public, max-age=0, s-maxage=3600',
    },
  });
}
